void gm8773c_suspend(void)
{
	u8 index;
	int start=0;
	struct dcs_setting_entry *dcs_cmd = common_display_off;
	int count = sizeof(common_display_off)/sizeof(common_display_off[0]);

	for (index = start; index < start + count; index++) {

		if (dcs_cmd[index].cmd_name == DELAY) {
			mdelay(dcs_cmd[index].para_list[0]);
		} else {
			dcs_cmd[index].cmd = 0xf0;
			gm8773c_tx_write_bytes(dcs_cmd[index].cmd,
					dcs_cmd[index].data_id, dcs_cmd[index].para_list, dcs_cmd[index].count);
			gm8773c_mipi_tx_write(0xfb,0xaa);
			gm8773c_mipi_tx_write(0xfb,0xbb);
		}
	}
}
EXPORT_SYMBOL(gm8773c_suspend);

