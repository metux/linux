void gm8773c_parse_initcmd_v2(struct dcs_setting_entry *dcs_setting_table, int start, int count)
{
	u8 index, i;

	for (index = start; index < start + count; index++) {

		if (dcs_setting_table[index].cmd_name == DELAY) { 
			mdelay(dcs_setting_table[index].para_list[0]);
			continue;
		}

		dcs_setting_table[index].cmd = 0xef;

		gm8773c_mipi_tx_write(0xed, 0x01);
		gm8773c_mipi_tx_write(0xee, 0x01);
		
		gm8773c_mipi_tx_write(dcs_setting_table[index].cmd, dcs_setting_table[index].data_id); //data_id
		if ((dcs_setting_table[index].data_id == 0x39) || (dcs_setting_table[index].data_id == 0x29)) {
			gm8773c_mipi_tx_write(dcs_setting_table[index].cmd, dcs_setting_table[index].count); //sizeL
			gm8773c_mipi_tx_write(dcs_setting_table[index].cmd, 0x00); //sizeH
		}
		for (i = 0; i < dcs_setting_table[index].count; i++) { //Leo add for mipi prot 1
			gm8773c_mipi_tx_write(dcs_setting_table[index].cmd, dcs_setting_table[index].para_list[i]);
		}

		gm8773c_mipi_tx_write(dcs_setting_table[index].cmd, dcs_setting_table[index].data_id); //data_id
		if ((dcs_setting_table[index].data_id == 0x39) || (dcs_setting_table[index].data_id == 0x29)) {
			gm8773c_mipi_tx_write(dcs_setting_table[index].cmd, dcs_setting_table[index].count); //sizeL
			gm8773c_mipi_tx_write(dcs_setting_table[index].cmd, 0x00); //sizeH
		}
		for (i = 0; i < dcs_setting_table[index].count; i++) { //Leo add for mipi prot 2
			gm8773c_mipi_tx_write(dcs_setting_table[index].cmd, dcs_setting_table[index].para_list[i]);
		}

		gm8773c_mipi_tx_write(0xfb, 0xee);
	}
}


