void gm8773c_init_cmds(struct dcs_setting_entry_1 *dcs_setting_table, int start, int count)
{
	u8 index, i;
	for (index = start; index < start + count; index++) {
		if (dcs_setting_table[index].data_id == DELAY_ID) {
			mdelay(dcs_setting_table[index].para_list[0]);
		} else {
			gm8773c_mipi_tx_write(0xed, 0x01);
			gm8773c_mipi_tx_write(0xee, 0x01);
			for (i = 0; i < dcs_setting_table[index].count; i++) {
				gm8773c_mipi_tx_write(dcs_setting_table[index].data_id, dcs_setting_table[index].para_list[i]);
				//printk("cmd para: 0x%02x\n", dcs_setting_table[index].para_list[i]);
			}
			gm8773c_mipi_tx_write(0xfb, 0xee);
		}
	}

	gm8773c_mipi_tx_write(0xff, 0x01);
}

int gm8773c_tx_write_bytes(u8 reg, u8 cmd,u8 *data,u16 data_len) //f0 type , only need write once
{
	unsigned char buf[128];
	int ret,count, ic_reg_shift, mipi_cmd_shift;

	memset(buf, 0x00, 128);

	buf[0] = reg;
	buf[1] = cmd;
	if ((cmd == 0x39) || (cmd == 0x29)) {
		buf[2] = data_len & 0xFF;
		buf[3] = (data_len >> 8) & 0xFF;
		ic_reg_shift = 1;
		mipi_cmd_shift = 3;
	} else {
		ic_reg_shift = 1;
		mipi_cmd_shift = 1;
	}

	memcpy(buf + ic_reg_shift + mipi_cmd_shift, data, data_len); //tx0 data 
	//tx1 memcpy(tx1_begin_addr, tx0_cmd_data_len_begin_addr, tx1_cmd_data_len);
	//memcpy(buf + ic_reg_shift + mipi_cmd_shift + data_len, buf + ic_reg_shift, data_len + mipi_cmd_shift); //tx1 data


	count = ic_reg_shift + mipi_cmd_shift + data_len; //reg+(cmd+data)*2(tx0/tx1)

#if 0 //debug
	{
		int i;
		for (i = 0; i < count; i++) {
			printk("0x%.2x ",buf[i]);
		}
		printk("count:%d ", count);
		printk("\n");
	}
#endif

	ret = it6112_write_bytes(MIPITX_ADDR, buf, count);

	return ret;
}

