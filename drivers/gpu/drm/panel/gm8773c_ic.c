void gm8773c_parse_initcmd_v2_f0(struct dcs_setting_entry *dcs_setting_table, int start, int count)
{
	u8 index;

	for (index = start; index < start + count; index++) {

		if (dcs_setting_table[index].cmd_name == DELAY) {
			mdelay(dcs_setting_table[index].para_list[0]);
		} else {
			dcs_setting_table[index].cmd = 0xf0;
			gm8773c_tx_write_bytes(dcs_setting_table[index].cmd,
					dcs_setting_table[index].data_id, dcs_setting_table[index].para_list, dcs_setting_table[index].count);
			gm8773c_mipi_tx_write(0xfb,0xaa);
			gm8773c_mipi_tx_write(0xfb,0xbb);
		}
	}
}
