void it6112_mipi_power_off(void)
{
	int dcs_table_size = DCS_TABLE_SIZE;
	struct it6112 *it6112;

#if IS_ENABLED(CONFIG_IT6112_GM87553C_SUPPORT) //Leo 20230413
	pr_info("%s Leo is_it6112:%d \n",__func__,is_it6112);
	if (is_it6112 == false) {
		pr_info("Leo gm8773c_suspend \n");
		gm8773c_suspend();
		return;
	}
#endif

	it6112 = &it6112_dev;
	/* for it6112 if lp with no clock, fire command will be failed, so need to switch continuous clock */
	it6112->enable_mipi_tx_output_clock_continuous = 1;
	it6112_mipi_tx_set_bits(0x44, 0x01, it6112->enable_mipi_tx_output_clock_continuous);
	mdelay(10);

	mipi_tx_write_dcs_cmds(dcs_table, dcs_table_size, SET_DISPLAY_OFF, 1);
	mdelay(10);
	mipi_tx_write_dcs_cmds(dcs_table, dcs_table_size, ENTER_SLEEP_MODE, 1);
	it6112_mipi_tx_set_bits(0x05, 0xFE, 0xFE);
	it6112_mipi_rx_set_bits(0x05, 0x03, 0x03);
	it6112_mipi_tx_set_bits(0x06, 0x02, 0x02);
	ITE_DEBUG_DRIVER("\n\rit6112 mipi power off");
}
EXPORT_SYMBOL(it6112_mipi_power_off);

void it6112_mipi_power_on(void)
{
	/* Video Clock Domain Reset */
	it6112_mipi_tx_set_bits(0x06, 0x02, 0x00);
	mdelay(2);
	it6112_mipi_rx_set_bits(0x05, 0x0F, 0x00);
	/* tx mclk still hold */
	it6112_mipi_tx_set_bits(0x05, 0xCC, 0x00);
	mdelay(2);
	ITE_DEBUG_DRIVER("\n\rit6112 mipi power on");
}

