	int link0_data_count, link0_cmd_type, link1_data_count, link1_cmd_type, i;

	ITE_DEBUG_DRIVER("\n\rread_panel cmd_name:%d", start);
	mipi_tx_write_dcs_cmds(dcs_setting_table, dcs_table_size, start, 1);
