void mipi_tx_setup_pattern_generator_video_format(struct it6112 *it6112)
{
	struct mipi_display_mode *display_mode = &it6112->mipi_rx_display_mode;
	int m_hdisplay = display_mode->m_hdisplay * 3 / 2, m_hfront_porch = display_mode->m_hfront_porch * 4 / 2;
	int m_hback_porch = display_mode->m_hback_porch * 4 / 2, m_hsync_width = display_mode->m_hsync_width * 4 / 2;
	int m_htotal = m_hfront_porch + m_hsync_width + m_hback_porch + m_hdisplay;

	it6112_mipi_tx_write(0x91, (it6112->mipi_tx_pattern_generator_color_depth << 4) | it6112->mipi_tx_pattern_generator_format);
	it6112_mipi_tx_write(0x92, it6112->mipi_tx_pattern_generator_base);
	it6112_mipi_tx_write(0x93, it6112->mipi_tx_pattern_generator_v_inc);
	it6112_mipi_tx_write(0x94, it6112->mipi_tx_pattern_generator_h_inc);
	it6112_mipi_tx_write(0x95, display_mode->m_vsync_width);
	it6112_mipi_tx_write(0x96, m_htotal & 0xFF);
	it6112_mipi_tx_write(0x97, (m_htotal & 0xFF00) >> 8);
	it6112_mipi_tx_write(0x98, m_hdisplay & 0xFF);
	it6112_mipi_tx_write(0x99, (m_hdisplay & 0xFF00) >> 8);
	it6112_mipi_tx_write(0x9A, m_hback_porch & 0xFF);
	it6112_mipi_tx_write(0x9B, (m_hback_porch & 0xFF00) >> 8);
	it6112_mipi_tx_write(0x9C, m_hsync_width & 0xFF);
	it6112_mipi_tx_write(0x9D, (m_hsync_width & 0xFF00) >> 8);
	it6112_mipi_tx_write(0x9E, display_mode->m_vtotal & 0xFF);
	it6112_mipi_tx_write(0x9F, (display_mode->m_vtotal & 0xFF00) >> 8);
	it6112_mipi_tx_write(0xA0, display_mode->m_vdisplay & 0xFF);
	it6112_mipi_tx_write(0xA1, (display_mode->m_vdisplay & 0xFF00) >> 8);
	it6112_mipi_tx_write(0xA2, display_mode->m_vback_porch & 0xFF);
	it6112_mipi_tx_write(0xA3, (display_mode->m_vback_porch & 0xFF00) >> 8);
}

