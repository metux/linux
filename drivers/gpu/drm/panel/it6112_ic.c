void mipi_polling_state(struct it6112 *it6112)
{
	int i, reg0e, reg0d, times = 10;

	for (i = 0; i < times; i++) {
		reg0e = it6112_mipi_tx_read(0x0E);
		reg0d = it6112_mipi_rx_read(0x0D);
		ITE_DEBUG_DRIVER("\n\rpolling tx state reg0x0E;0x%02x, rx state reg0x0D:0x%02x", reg0e, reg0d);

		if ((reg0e & 0x27) != 0x00) {
			mipi_tx_reset(it6112);
		} else {
			mipi_tx_enable_ppi(it6112);
			return;
		}

		mdelay(2);
	}
	mipi_tx_enable_ppi(it6112);
}

void it6112_calc_rclk(struct it6112 *it6112)
{
	int rddata, i, sum, retry = 1;

	sum = 0;
	for(i = 0; i < retry; i++) {
		/* enable rclk 100ms counter */
		it6112_mipi_rx_set_bits(0x94, 0x80, 0x80);
		mdelay(100);
		it6112_mipi_rx_set_bits(0x94, 0x80, 0x00);

		rddata = it6112_mipi_rx_read(0x95);
		rddata += (it6112_mipi_rx_read(0x96) << 8);
		rddata += (it6112_mipi_rx_read(0x97) << 16);

		sum += rddata;
	}
	sum /= retry;

	it6112->mipi_rx_rclk = sum / 100;

	ITE_DEBUG_DRIVER("\n\rRCLK=%dMHz", it6112->mipi_rx_rclk / 1000);
}

void it6112_calc_mclk(struct it6112 *it6112)
{
	int i, rddata, sum, retry = 1;

	sum = 0;
	for(i = 0; i < retry; i++) {
		it6112_mipi_rx_set_bits(0x9B, 0x80, 0x80);
		mdelay(2);
		it6112_mipi_rx_set_bits(0x9B, 0x80, 0x00);

		rddata = it6112_mipi_rx_read(0x9A);
		rddata = ((it6112_mipi_rx_read(0x9B) & 0x0F) << 8) + rddata;

		sum += rddata;
	}

	sum /= retry;

	it6112->mipi_rx_mclk = it6112->mipi_rx_rclk * 2048 / sum;
	ITE_DEBUG_DRIVER("\n\rMCLK = %dMHz", it6112->mipi_rx_mclk / 1000);
}

int it6112_mipi_rx_read_word(unsigned int reg)
{
	int val_0, val_1;

	val_0 = it6112_mipi_rx_read(reg);

	if (val_0 < 0)
		return val_0;

	val_1 = it6112_mipi_rx_read(reg + 1);

	if (val_1 < 0)
		return val_1;

	return (val_1 << 8) | val_0;
}

