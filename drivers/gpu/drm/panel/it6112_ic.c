	ITE_DEBUG_DRIVER("\n\rlink0_data_count(reg0x7A):0x%02x, link0_cmd_type(reg0x7B):0x%02x", link0_data_count, link0_cmd_type);
	ITE_DEBUG_DRIVER("\n\rlink1_data_count(reg0x7D):0x%02x, link1_cmd_type(reg0x7E):0x%02x", link1_data_count, link1_cmd_type);

	for (i = 0; i < link0_data_count; i++)
		ITE_DEBUG_DRIVER("\n\rlink0_data[%d]:0x%02x", i, it6112_mipi_tx_read(0x79));

	for (i = 0; i < link1_data_count; i++)
		ITE_DEBUG_DRIVER("\n\rlink1_data[%d]:0x%02x", i, it6112_mipi_tx_read(0x7C));
