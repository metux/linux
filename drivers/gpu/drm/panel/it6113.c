void mipi_rx_init(struct it6112 *it6112)
{
	//Enable MPRX interrupt
	mipi_rx_write(0x09, 0xFF);
	mipi_rx_write(0x0A, 0xFF);
	mipi_rx_write(0x0B, 0x3F);
	mipi_rx_write(0x05, 0x03);
	mipi_rx_write(0x05, 0x00);

	/* Setup INT Pin: Active Low */
	mipi_rx_set_bits(0x0C, 0x0F, (it6112->enable_mipi_rx_lane_swap << 3)|(it6112->enable_mipi_rx_pn_swap << 2)| 0x03);
	mipi_rx_set_bits(0x11, 0x01, it6112->enable_mipi_rx_mclk_inverse);
	mipi_rx_set_bits(0x18, 0xff, 0x43);
	mipi_rx_set_bits(0x19, 0xf3, 0x03);
	mipi_rx_set_bits(0x20, 0xf7, 0x03);
	/* rx auto detect video format */
	mipi_rx_set_bits(0x21, 0x08, 0x08);
	mipi_rx_set_bits( 0x44, 0x22, 0x22);
	mipi_rx_write(0x27, it6112->mipi_rx_video_type);
	mipi_rx_write(0x72, 0x07);
	/* previous setting is 0x03 */
	mipi_rx_set_bits(0x8A, 0x07, 0x02);
	mipi_rx_set_bits(0xA0, 0x01, 0x01);
	if (it6112->enable_mipi_4_lane_mode)
		mipi_rx_set_bits(0x80, 0x3F, 0x03);
	else
		mipi_rx_set_bits(0x80, 0x3F, 0x07);

	//ITE_DEBUG_DRIVER(("\n\rMPRX initial done!"));
}

