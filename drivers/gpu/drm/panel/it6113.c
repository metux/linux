void mipi_tx_calc_hs_para(struct it6112 *it6112)
{
	u32 mclk_ps, mipi_tx_calc_hs_end_time;

	printk("renable hs auto set\n");
	printk("rdefault reg0x22:0x%02x, reg0x1F:0x%02x\n", it6112->mipi_tx_hs_pretime, it6112->mipi_tx_hs_end_time);

	if (it6112->mipi_rx_mclk == 0) {
		printk("mipi rx mclk = 0, error! use default reg0x22, reg0x1F\n");
		return;
	}

	mclk_ps = 1000000000 / it6112->mipi_rx_mclk;

	if (mclk_ps == 0) {
		printk(" mipi mclk_ps = 0, error! use default reg0x22, reg0x1F\n");
		return;
	}

	mipi_tx_calc_hs_end_time = (6 * mclk_ps - 20 * 1000) / mclk_ps;

	if (!it6112->enable_mipi_4_lane_mode)
		mclk_ps *= 2;

	it6112->mipi_tx_hs_pretime = (((145 + ((4 + it6112->mipi_tx_lpx_num) * it6112->mipi_tx_oclk_ns)) * 1000 - ((3 * mclk_ps) >> 1)) / mclk_ps) + 20;
	it6112->mipi_tx_hs_end_time = mipi_tx_calc_hs_end_time + 9;

	if (mipi_tx_calc_hs_end_time <= 0)
		it6112->mipi_tx_hs_end_time = 3;

	printk("%s lanes mode, mclk_ns: %d.%d ns\n", it6112->enable_mipi_4_lane_mode ? "4" : "8", mclk_ps / 1000, mclk_ps % 1000);
	printk("calc reg0x22:0x%02x, reg0x1F:0x%02x, lpx_num:0x%02x\n",
					it6112->mipi_tx_hs_pretime, it6112->mipi_tx_hs_end_time, it6112->mipi_tx_lpx_num);
}

