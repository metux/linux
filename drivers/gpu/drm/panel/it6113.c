void poll(struct it6112 *it6112)
{
	int reg0d;

	reg0d = mipi_rx_read(0x0D);
	printk("it6112 poll rx reg0D:0x%02x enable_ppi:%d\n", reg0d, it6112->enable_ppi);

	if ((reg0d & 0x10) && (reg0d & 0x08)) {
		printk("it6112 rx clock not stable\n");
		mipi_rx_reset(it6112);
		return;
	}

	if (reg0d & 0x10) {
		if (it6112->enable_ppi) {
			if (!mipi_tx_state())
				device_esd_reinit(it6112);
		} else {
			mipi_polling_state(it6112);
		}
	}
}

