static int it6112_i2c_driver_probe(struct i2c_client *client, const struct i2c_device_id *id)
{
	int err=0;

	pr_err("[it6112_i2c_driver_probe] start!\n");

	if(match_id(client, &it6112_i2c_id[0])) {
		if (!(it6112_mipirx = kmalloc(sizeof(struct i2c_client), GFP_KERNEL)))
		{
			err = -ENOMEM;
			goto exit;
		}

		memset(it6112_mipirx, 0, sizeof(struct i2c_client));

		it6112_mipirx = client;
	} else {
		pr_err("[it6112_i2c_driver_probe] error!\n");

		err = -EIO;
		goto exit;
	}

	pr_err("[it6112_i2c_driver_probe] %s i2c sucess!\n", client->name);

	it6112_config_proc = proc_create(IT6112_CONFIG_PROC_FILE, 0660, NULL,
					 &it6112_upgrade_proc_fops);
	if (it6112_config_proc == NULL) {
		pr_err("create_proc_entry %s failed",
			  IT6112_CONFIG_PROC_FILE);
	}

#if IS_ENABLED(CONFIG_CM_MIDMISC_SUPPORT) //Leo 20240424
	it6112_dev.chip_id = cust_midmisc_get_dualmipi_chipid();
#endif

#if IS_ENABLED(CONFIG_MID_CSCI_SUPPORT) //Leo 20240409
	if (csci_exist("lcm.oled.max.brightness")) { 
		cust_oled_max_brightness = csci_integer("lcm.oled.max.brightness", 0);
	}
#endif

	pr_err("create_proc_entry ok\n");
	
	return 0;

exit:
	return err;
}

