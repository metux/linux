void mipi_tx_init(struct it6112 *it6112)
{
	u8 mipi_tx_link_lane_config = ((it6112->enable_mipi_tx_link_swap << 3) | (it6112->enable_mipi_tx_lane_swap << 1) | it6112->enable_mipi_tx_pn_swap);
	
	/* software reset all, include RX!! */
	mipi_tx_write(0x05, 0xFE);
	mipi_tx_write(0x05, 0x00);
	mipi_tx_set_bits(0x05, 0x01, 0x01);
	mipi_tx_set_bits(0x05, 0x20, 0x20);
	mipi_tx_set_bits(0xD0, 0x04, it6112->enable_mipi_tx_external_mclk << 2);
	mipi_tx_set_bits(0x8C, 0x0B, mipi_tx_link_lane_config);
	mdelay(2);

	mipi_tx_setup_lps(it6112);
	mipi_tx_setup_lp_11_time(it6112);
	mipi_tx_set_bits(0x10, 0x20, OUTPUT_AS_RX_INPUT_MODE ? 0x00 : 0x20);
	mipi_tx_write(0x22, it6112->mipi_tx_hs_pretime);

	if (!it6112->enable_mipi_tx_output_clock_continuous)
		mipi_tx_set_bits(0x46, 0xF0, 0xF0);

	if (!OUTPUT_AS_RX_INPUT_MODE)
		mipi_tx_set_bits(0x11, 0x10, it6112->mipi_tx_sync_pulse ? 0x00 : 0x10);

	mipi_tx_set_bits(0x10, 0x02, (it6112->enable_mipi_tx_mclk_inverse << 1));
	mipi_tx_set_bits(0x11, 0x08, (it6112->enable_mipi_4_lane_mode << 3));
	mipi_tx_set_bits(0x3C, 0x20, 0x20);
	mipi_tx_set_bits(0x44, 0x04, it6112->enable_mipi_tx_pre_1t << 2);
	mipi_tx_set_bits(0x45, 0x0f, it6112->mipi_tx_lpx_num);
	mipi_tx_set_bits(0x47, 0xf0, it6112->mipi_tx_hs_prepare << 4);
	mipi_tx_set_bits(0xB0, 0xFF, 0x27);
	mipi_tx_write(0x1f, it6112->mipi_tx_hs_end_time);
	
	if (it6112->chip_id == IT6113) {
		/* enable mipi tx non continuous clock hs fire lp not depends on mipi clock */
		mipi_tx_set_bits(0x78, 0x20, 0x20);
	}

	mipi_tx_adjusted_oclk(it6112);
	printk("mipi tx initial done! set reg0x22: 0x%02x, reg0x1F:0x%02x, lpx_num:0x%02x\n",
				it6112->mipi_tx_hs_pretime, it6112->mipi_tx_hs_end_time, it6112->mipi_tx_lpx_num);	
}

void get_support_feature(struct it6112 *it6112)
{
	switch (it6112->chip_id) {
	case IT6112:
		if (!OUTPUT_AS_RX_INPUT_MODE && !it6112->mipi_tx_sync_pulse) {
			printk("\not support sync event, output sync pulse\n");
			it6112->mipi_tx_sync_pulse = true;
		}
		break;

	case IT6113:

		if (!it6112->enable_mipi_tx_h_enter_lps) {
			printk("not support h fire packet\n");
			it6112->enable_mipi_tx_h_fire_packet = false;
		}

		if (it6112->enable_mipi_tx_link_swap && it6112->revision < 0xD0) {
			//ITE_DEBUG_DRIVER("\n\rnot support tx link swap!");
			it6112->enable_mipi_tx_link_swap = 0;
		}
		
		break;

	default:
		break;
	}

	/* this value depends on mclk */
	//it6112->mipi_tx_hs_pretime = it6112->enable_mipi_tx_output_clock_continuous ? ((it6112->chip_id == IT6112) ? 0x20 : 0x40) : 0x40;
}

void device_init(struct it6112 *it6112)
{
	get_support_feature(it6112);
	mipi_rx_init(it6112);

	mdelay(30);
	mipi_rx_calc_rclk(it6112);
	mipi_rx_calc_mclk(it6112);
	mdelay(30);

	if (it6112->enable_mipi_tx_hs_auto_set)
		mipi_tx_calc_hs_para(it6112);

	mipi_tx_init(it6112);
}

