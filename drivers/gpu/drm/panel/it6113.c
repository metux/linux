static unsigned char chip_check_rxid(void)
{
    unsigned char reg0, reg1;
    reg0 = mipi_rx_read(0x00);
    reg1 = mipi_rx_read(0x01);

    if (reg0==0x54 && reg1==0x49)
    {
        return 1;
    }
    else
    {
        return 0;
    }
}

static unsigned char chip_check_txid(void)
{
    unsigned char reg0, reg1;
    reg0 = mipi_tx_read(0x00);
    reg1 = mipi_tx_read(0x01);

    if (reg0==0x54 && reg1==0x49)
    {
        return 1;
    }
    else
    {
        return 0;
    }
}

u8 chip_identify(struct it6112 *it6112)
{
	unsigned char test_counter = 0;
	unsigned char tx_find=0, rx_find=0;

	 if (mipi_tx_read(0x02) == 0x12) { //Leo 20230816
		it6112->chip_id = IT6112;
		pr_info("it611x found it6112 \n");
		return 1;
	 }

	do{
		test_counter++;

		if (chip_check_txid()==1) 
		{	
			it6112->revision = mipi_tx_read(0x04);

			switch (mipi_tx_read(0x02)) {
			case 0x12:
				it6112->chip_id = IT6112;
				break;

			case 0x13:
				it6112->chip_id = IT6113;
					printk("it611x found IT6113");
				break;

				default:
					it6112->chip_id = GM8773C;
					printk("it611x found GM8773C");
					break;
			}
			
			if(it6112->chip_id != 0x00)
			{
				mdelay(1);
				if(1)//(enable_reset)
				{
					mipi_tx_set_bits(0x05, 0x01, 0x01);
				}
				tx_find = 1;
				break;
			}	
		}
		
		mdelay(5);
	}while(test_counter <= 20);

	if (it6112->chip_id == GM8773C) {
		return 0;
	}

	test_counter = 0;
	do{
		test_counter++;
		if (chip_check_rxid()==1) 
		{	
			rx_find = 1;
			if(1)//(enable_reset)
			{
				mipi_rx_set_bits(0x05, 0x04, 0x04);
			}
			break;
		}
		mdelay(5);
	}while(test_counter <= 20);
	
	
	if(tx_find && rx_find)
	{
		test_counter = 0;
		do{
			test_counter++;
			if ( (chip_check_rxid()==1) && (chip_check_txid()==1) )
			{	
				//ITE_DEBUG_DRIVER("find %s, rev: 0x%02x", id_name[it6112->chip_id], it6112->revision);
				return 1;
			}
			mdelay(5);
		}while(test_counter <= 20);
	}

	printk("can not find chip");

	return 0;
}

