int get_dcs_ecc(int dcshead)
{
	int q0, q1, q2, q3, q4, q5;

	q0 = ((dcshead >> 0) & (0x01)) ^ ((dcshead >> 1) & (0x01)) ^ ((dcshead >> 2) & (0x01)) ^ ((dcshead >> 4) & (0x01)) ^ ((dcshead >> 5) & (0x01)) ^
		((dcshead >> 7) & (0x01)) ^ ((dcshead >> 10) & (0x01)) ^ ((dcshead >> 11) & (0x01)) ^ ((dcshead >> 13) & (0x01)) ^ ((dcshead >> 16) & (0x01)) ^
		((dcshead >> 20) & (0x01)) ^ ((dcshead >> 21) & (0x01)) ^ ((dcshead >> 22) & (0x01)) ^ ((dcshead >> 23) & (0x01));
	q1 = ((dcshead >> 0) & (0x01)) ^ ((dcshead >> 1) & (0x01)) ^ ((dcshead >> 3) & (0x01)) ^ ((dcshead >> 4) & (0x01)) ^ ((dcshead >> 6) & (0x01)) ^
		((dcshead >> 8) & (0x01))  ^ ((dcshead >> 10) & (0x01)) ^ ((dcshead >> 12) & (0x01)) ^ ((dcshead >> 14) & (0x01)) ^ ((dcshead >> 17) & (0x01)) ^
		((dcshead >> 20) & (0x01)) ^ ((dcshead >> 21) & (0x01)) ^ ((dcshead >> 22) & (0x01)) ^ ((dcshead >> 23) & (0x01)) ;
	q2 = ((dcshead >> 0) & (0x01)) ^ ((dcshead>> 2) & (0x01)) ^ ((dcshead >> 3) & (0x01)) ^ ((dcshead >> 5) & (0x01)) ^ ((dcshead >> 6) & (0x01)) ^
		((dcshead >> 9) & (0x01)) ^ ((dcshead >> 11) & (0x01)) ^ ((dcshead >> 12) & (0x01)) ^ ((dcshead >> 15) & (0x01)) ^ ((dcshead >> 18) & (0x01)) ^
		((dcshead >> 20) & (0x01)) ^ ((dcshead >> 21) & (0x01)) ^ ((dcshead >> 22) & (0x01));
	q3 = ((dcshead >> 1) & (0x01)) ^ ((dcshead>> 2) & (0x01)) ^ ((dcshead >> 3) & (0x01)) ^ ((dcshead >> 7) & (0x01)) ^ ((dcshead >> 8) & (0x01)) ^
		((dcshead >> 9) & (0x01)) ^ ((dcshead >> 13) & (0x01)) ^ ((dcshead >> 14) & (0x01)) ^ ((dcshead >> 15) & (0x01)) ^ ((dcshead >> 19) & (0x01)) ^
		((dcshead >> 20) & (0x01)) ^ ((dcshead >> 21) & (0x01)) ^ ((dcshead >> 23) & (0x01));
	q4 = ((dcshead >> 4) & (0x01)) ^ ((dcshead >> 5) & (0x01)) ^ ((dcshead >> 6) & (0x01)) ^ ((dcshead >> 7) & (0x01)) ^ ((dcshead >> 8) & (0x01)) ^
		((dcshead >> 9) & (0x01)) ^ ((dcshead >> 16) & (0x01)) ^ ((dcshead >> 17) & (0x01)) ^ ((dcshead >> 18) & (0x01)) ^ ((dcshead >> 19) & (0x01)) ^
		((dcshead >> 20) & (0x01)) ^ ((dcshead >> 22) & (0x01)) ^ ((dcshead >> 23) & (0x01));
	q5 = ((dcshead >> 10) & (0x01)) ^ ((dcshead >> 11) & (0x01)) ^ ((dcshead >> 12) & (0x01)) ^ ((dcshead >> 13) & (0x01)) ^ ((dcshead >> 14) & (0x01)) ^
		((dcshead >> 15) & (0x01)) ^ ((dcshead >> 16) & (0x01)) ^ ((dcshead >> 17) & (0x01)) ^ ((dcshead >> 18) & (0x01)) ^ ((dcshead >> 19) & (0x01)) ^
		((dcshead >> 21) & (0x01)) ^ ((dcshead >> 22) & (0x01)) ^ ((dcshead >> 23) & (0x01));
	//	printf("q0= %x q1=%x\n", q0, q1);
	return (q0 + (q1 << 1) + (q2 << 2) + (q3 << 3) + (q4 << 4) + (q5 << 5));
}

int dcs_crc8t(int crcq16b, const u8 crc8bin)
{
	int lfsrout = 0, lfsr[16], i;

	lfsr[15] = ((crc8bin >> 7) & 0x01) ^ ((crc8bin >> 3) & 0x01) ^
		   ((crcq16b >> 7) & 0x01) ^ ((crcq16b >> 3) & 0x01);
	lfsr[14] = ((crc8bin >> 6) & 0x01) ^ ((crc8bin >> 2) & 0x01) ^
		   ((crcq16b >> 6) & 0x01) ^ ((crcq16b >> 2) & 0x01);
	lfsr[13] = ((crc8bin >> 5) & 0x01) ^ ((crc8bin >> 1) & 0x01) ^
		   ((crcq16b >> 5) & 0x01) ^ ((crcq16b >> 1) & 0x01);
	lfsr[12] = ((crc8bin >> 4) & 0x01) ^ ((crc8bin >> 0) & 0x01) ^
		   ((crcq16b >> 4) & 0x01) ^ ((crcq16b >> 0) & 0x01);
	lfsr[11] = ((crc8bin >> 3) & 0x01) ^
		   ((crcq16b >> 3) & 0x01);
	lfsr[10] = ((crc8bin >> 7) & 0x01) ^ ((crc8bin >> 3) & 0x01) ^ ((crc8bin >> 2) & 0x01) ^
		   ((crcq16b >> 7) & 0x01) ^ ((crcq16b >> 3) & 0x01) ^ ((crcq16b >> 2) & 0x01);
	lfsr[9] = ((crc8bin >> 6) & 0x01) ^ ((crc8bin >> 2) & 0x01) ^ ((crc8bin >> 1) & 0x01) ^
		  ((crcq16b >> 6) & 0x01) ^ ((crcq16b >> 2) & 0x01) ^ ((crcq16b >> 1) & 0x01);
	lfsr[8] = ((crc8bin >> 5) & 0x01) ^ ((crc8bin >> 1) & 0x01) ^ ((crc8bin >> 0) & 0x01) ^
		  ((crcq16b >> 5) & 0x01) ^ ((crcq16b >> 1) & 0x01) ^ ((crcq16b >> 0) & 0x01);
	lfsr[7] = ((crc8bin >> 4) & 0x01) ^ ((crc8bin >> 0) & 0x01) ^
		  ((crcq16b >> 15) & 0x01) ^ ((crcq16b >> 4) & 0x01) ^ ((crcq16b >> 0) & 0x01);
	lfsr[6] = ((crc8bin >> 3) & 0x01) ^
		  ((crcq16b >> 14) & 0x01) ^ ((crcq16b >> 3) & 0x01);
	lfsr[5] = ((crc8bin >> 2) & 0x01) ^
		  ((crcq16b >> 13) & 0x01) ^ ((crcq16b >> 2) & 0x01);
	lfsr[4] = ((crc8bin >> 1) & 0x01) ^
		  ((crcq16b >> 12) & 0x01) ^ ((crcq16b >> 1) & 0x01);
	lfsr[3] = ((crc8bin >> 7) & 0x01) ^ ((crc8bin >> 3) & 0x01) ^ ((crc8bin >> 0) & 0x01) ^
		  ((crcq16b >> 11) & 0x01) ^ ((crcq16b >> 7) & 0x01) ^ ((crcq16b >> 3) & 0x01) ^ ((crcq16b >> 0) & 0x01);
	lfsr[2] = ((crc8bin >> 6) & 0x01) ^ ((crc8bin >> 2) & 0x01) ^
		  ((crcq16b >> 10) & 0x01) ^ ((crcq16b >> 6) & 0x01) ^ ((crcq16b >> 2) & 0x01);
	lfsr[1] = ((crc8bin >> 5) & 0x01) ^ ((crc8bin >> 1) & 0x01) ^
		  ((crcq16b >> 9) & 0x01) ^ ((crcq16b >> 5) & 0x01) ^ ((crcq16b >> 1) & 0x01);
	lfsr[0] = ((crc8bin >> 4) & 0x01) ^ ((crc8bin >> 0) & 0x01) ^
		  ((crcq16b >> 8) & 0x01) ^ ((crcq16b >> 4) & 0x01) ^ ((crcq16b >> 0) & 0x01);

	for (i = 0; i < sizeof(lfsr) / sizeof(lfsr[0]); i++)
		lfsrout = lfsrout + (lfsr[i]<<i);

	return lfsrout;
}

int get_dcs_crc(int bytenum, const u8 *crcbyte)
{
	int i, crctemp = 0xFFFF;

	for (i = 0; i <= bytenum - 1; i++)
		crctemp = dcs_crc8t(crctemp, crcbyte[i]);

	return crctemp;
}

void mipi_tx_setup_long_packet_header(struct mipi_packet *pheader, u32 word_count)
{
	int header;

	pheader->word_count_h = word_count >> 8;
	pheader->word_count_l = (u8)word_count;
	header = pheader->data_id | pheader->word_count_h << 16 | pheader->word_count_l << 8;
	pheader->ecc = get_dcs_ecc(header);
}

enum mipi_packet_size mipi_tx_get_packet_size(const struct dcs_setting_entry *dcs_setting_table, enum dcs_cmd_name cmd_name)
{
	u8 i, size = sizeof(packet_size_data_id_map) / sizeof(packet_size_data_id_map[0]);

	for (i = 0; i < size; i++) {
		if (dcs_setting_table[cmd_name].data_id == packet_size_data_id_map[i].data_id)
			break;
	}

	if (i == size) {
		if (dcs_setting_table[cmd_name].count == 0) {
			printk("error! cmd index: %d count = 0", cmd_name);
			return UNKNOWN_PACKET;
		} else if (dcs_setting_table[cmd_name].count < 3) {
			return SHORT_PACKET;
		} else {
			return LONG_PACKET;
		}
	}

	return packet_size_data_id_map[i].packet_size;	

}

void mipi_tx_get_packet_fire_state(void)
{
	u8 lp_cmd_fifo, link0_data_fifo, link1_data_fifo;

	lp_cmd_fifo = mipi_tx_read(0x7F);
	link0_data_fifo = mipi_tx_read(0x80);
	link1_data_fifo = mipi_tx_read(0x81);

	if (lp_cmd_fifo != 0)
		printk("error! fire low power cmd fail, remain bytes not fire, reg0x7F:0x%02x\n", lp_cmd_fifo);
	if (link0_data_fifo != 0)
		printk("error! fire link0 low power data fail, remain %d bytes not fire, reg0x80:0x%02x\n", link0_data_fifo, link0_data_fifo);
	if (link1_data_fifo != 0)
		printk("error! fire link1 low power data fail, remain %d bytes not fire, reg0x81:0x%02x\n", link1_data_fifo, link1_data_fifo);
}

void mipi_tx_setup_packet(struct mipi_packet *pheader,
			  const struct dcs_setting_entry *dcs_setting_table,
			  enum dcs_cmd_name cmd_name)
{
	int short_cmd;
	enum mipi_packet_size packet_size;

	pheader->data_id = dcs_setting_table[cmd_name].data_id;
	packet_size = mipi_tx_get_packet_size(dcs_setting_table, cmd_name);

	if (packet_size == UNKNOWN_PACKET) {
//		ITE_DEBUG_DRIVER(("error! unknown packet size and check dcs table parameter"));
		return;
	}

	if (packet_size == SHORT_PACKET) {
		pheader->word_count_l = dcs_setting_table[cmd_name].para_list[0];
		pheader->word_count_h = dcs_setting_table[cmd_name].para_list[1];
		short_cmd = pheader->data_id | pheader->word_count_l << 8 | pheader->word_count_h << 16;
		pheader->ecc = get_dcs_ecc(short_cmd);
	}

	if (packet_size == LONG_PACKET)
		mipi_tx_setup_long_packet_header(pheader, dcs_setting_table[cmd_name].count);
}

inline void mipi_tx_fire_packet(const struct dcs_setting_entry *dcs_setting_table, enum dcs_cmd_name cmd_name)
{
	mipi_tx_write(0x75, dcs_setting_table[cmd_name].cmd);
}

void mipi_tx_setup_packet_process(struct it6112 *it6112, const struct dcs_setting_entry *dcs_setting_table, enum dcs_cmd_name cmd_name)
{
	struct mipi_packet packet;
	enum mipi_packet_size packet_size;
	u32 long_packet_checksum;
	int i, header_crc, data_count;

//	ITE_DEBUG_DRIVER(("\n\rcmd_name: %d count:%d", dcs_setting_table[cmd_name].cmd_name, dcs_setting_table[cmd_name].count));
	mipi_tx_setup_packet(&packet, dcs_setting_table, cmd_name);
	packet_size = mipi_tx_get_packet_size(dcs_setting_table, cmd_name);
//	ITE_DEBUG_DRIVER(("\n\r%s packet\n\r", packet_size == LONG_PACKET ? "long" : "short"));

	for (i = 0; i < sizeof(packet); i++) {
		mipi_tx_write(0x73, ((u8*)(&packet))[i]);
//		ITE_DEBUG_DRIVER(("data[%d]: 0x%02x ", i, ((u8*)(&packet))[i]));
	}

	if (packet_size == SHORT_PACKET) {
		header_crc = 2;
		goto short_packet;
	}

	header_crc = sizeof(packet) + 2;

	long_packet_checksum = get_dcs_crc(dcs_setting_table[cmd_name].count, dcs_setting_table[cmd_name].para_list);
	for (i = 0; i < dcs_setting_table[cmd_name].count; i++) {
		mipi_tx_write(0x73, dcs_setting_table[cmd_name].para_list[i]);
//		ITE_DEBUG_DRIVER(("\n\rcmd para: 0x%02x", dcs_setting_table[cmd_name].para_list[i]));
	}

	mipi_tx_write(0x73, (u8)long_packet_checksum);
	mipi_tx_write(0x73, (u8)(long_packet_checksum >> 8));
	//ITE_DEBUG_DRIVER("\n\rlong_packet_checksum_l: 0x%02x long_packet_checksum_h: 0x%02x", (u8)long_packet_checksum, (u8)(long_packet_checksum >> 8));

short_packet:

	switch (it6112->chip_id) {
	case IT6112:
		mipi_tx_write(0x74, 0x40 | (dcs_setting_table[cmd_name].count + header_crc));
		break;

	case IT6113:
		data_count = dcs_setting_table[cmd_name].count + header_crc;
		
		if (data_count == IT6113_LP_CMD_FIFO)
			data_count = 1;

		mipi_tx_write(0x74, (it6112->enable_mipi_tx_h_fire_packet << 7) | data_count);
		break;

	default:
		break;
	}

}

inline u8 mipi_tx_get_video_state()
{
	return mipi_tx_read(0x0E) & 0x10;
}

void mipi_tx_write_dcs_cmds(struct it6112 *it6112, const struct dcs_setting_entry *dcs_setting_table, int dcs_table_size, enum dcs_cmd_name start, int count)
{
	u16 i, data_count, enable_force_lp_mode = !mipi_tx_get_video_state();
	u8 lp_cmd_fifo_size[] = {LP_CMD_FIFO_SIZE, IT6112_LP_CMD_FIFO, IT6113_LP_CMD_FIFO };

	if (enable_force_lp_mode) {
		mipi_tx_set_bits(0x11, 0x80, 0x80);
		mipi_tx_set_bits(0x70, 0x04, 0x04);
	}

	mipi_tx_write(0x3D, 0x00);
	mipi_tx_write(0x3E, enable_force_lp_mode ? 0x00 : 0x10);
	mipi_tx_write(0x3F, enable_force_lp_mode ? 0x30 : 0x90);

	if (it6112->chip_id == IT6113 && it6112->revision >= 0xD0) {
		mipi_tx_write(0x3D, 0xFF);
		mipi_tx_write(0x3E, 0xFF);
		mipi_tx_write(0x3F, 0xD0);
	}
	
	for (i = start; i < start + count; i++) {
		printk("cmd:%d rx reg0d:0x%02x, tx reg0e:0x%02x\n", i, mipi_rx_read(0x0D), mipi_tx_read(0x0E));
		if (i >= dcs_table_size)
			goto complete_write_dcs;
		if (dcs_setting_table[i].cmd_name == DELAY) {
			mdelay(dcs_setting_table[i].cmd);
			continue;
		}

		data_count = dcs_setting_table[i].count + ((mipi_tx_get_packet_size(dcs_setting_table, i) == SHORT_PACKET) ? 2 : 6);

		if (data_count > lp_cmd_fifo_size[it6112->chip_id]) {
				printk("error! lp cmd: %d, exceed cmd fifo\n", i);
				continue;
		}

		mipi_tx_setup_packet_process(it6112, dcs_setting_table, i);
		mipi_tx_fire_packet(dcs_setting_table, i);
		if (enable_force_lp_mode)
			mipi_tx_get_packet_fire_state();
//		mdelay(10);   //yanjb 20210419
	}
	mdelay(10);

complete_write_dcs:
	if (i >= dcs_table_size && (start + count > dcs_table_size))
//		ITE_DEBUG_DRIVER(("\n\rerror! exceed maximum dcs setting table index"));

	if (enable_force_lp_mode) {
		mipi_tx_set_bits(0x11, 0x80, 0x00);
		mipi_tx_set_bits(0x70, 0x04, 0x00);
	}

	mdelay(20);
	
	if (!enable_force_lp_mode)
			mipi_tx_get_packet_fire_state();
}

