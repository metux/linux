void mipi_polling_state(struct it6112 *it6112)
{
	int i, reg0e, reg0d, times = 10;

	for (i = 0; i < times; i++) {
		reg0e = mipi_tx_read(0x0E);
		reg0d = mipi_rx_read(0x0D);

		printk("polling tx state reg0x0E:0x%02x, rx state reg0x0D:0x%02x\n", reg0e, reg0d);

		if ((reg0e & 0x27) != 0x00) {
			mipi_tx_reset(it6112);
		} else {
			break;
		}

		mdelay(2);
	}
	mipi_tx_enable_ppi(it6112);
	mdelay(30);
	printk("after enable ppi tx state reg0x0E:0x%02x, rx state reg0x0D:0x%02x\n", mipi_tx_read(0x0E), mipi_rx_read(0x0D));
}

void mipi_rx_calc_rclk(struct it6112 *it6112)
{
	int rddata, i, sum, retry = 1;

	sum = 0;
	for(i = 0; i < retry; i++) {
		/* enable rclk 100ms counter */
		mipi_rx_set_bits(0x94, 0x80, 0x80);
		mdelay(100);
		/* disable rclk 100ms counter */
		mipi_rx_set_bits(0x94, 0x80, 0x00);

		rddata = mipi_rx_read(0x95);
		rddata += (mipi_rx_read(0x96) << 8);
		rddata += (mipi_rx_read(0x97) << 16);

		sum += rddata;
	}
	sum /= retry;

	it6112->mipi_rx_rclk = sum / 100;

	//ITE_DEBUG_DRIVER(("\n\rRCLK=%dMHz", it6112->mipi_rx_rclk / 1000));
}

void mipi_rx_calc_mclk(struct it6112 *it6112)
{
	int i, rddata, sum, retry = 1;

	sum = 0;
	for(i = 0; i < retry; i++) {
		mipi_rx_set_bits(0x9B, 0x80, 0x80);
		mdelay(2);
		mipi_rx_set_bits(0x9B, 0x80, 0x00);

		rddata = mipi_rx_read(0x9A);
		rddata = ((mipi_rx_read(0x9B) & 0x0F) << 8) + rddata;

		sum += rddata;
	}

	sum /= retry;

	it6112->mipi_rx_mclk = it6112->mipi_rx_rclk * 2048 / sum;
	////ITE_DEBUG_DRIVER(("\n\rMCLK = %dMHz", mclk / 1000));
}

int mipi_rx_read_word(struct it6112 *it6112, unsigned int reg)
{
	int val_0, val_1;

	val_0 = mipi_rx_read(reg);

	if (val_0 < 0)
		return val_0;

	val_1 = mipi_rx_read(reg + 1);

	if (val_1 < 0)
		return val_1;

	return (val_1 << 8) | val_0;
}

