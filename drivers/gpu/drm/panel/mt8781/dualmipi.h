#define _INIT_DUALMIPI_CMD_ALL(x,y,z,...) { \
	.cmd_name = x, \
	.cmd = y, \
	.data_id = z, \
	.count = sizeof((unsigned char[]){__VA_ARGS__}), \
	.para_list = (unsigned char[]){__VA_ARGS__} }

